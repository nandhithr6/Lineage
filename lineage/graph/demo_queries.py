"""Focused queries for the FalkorDB browser (http://localhost:3000): small subgraphs a viewer can actually read.

Generates docs/demo_queries.md and, with --check, runs every query and fails if one returns nothing or too many elements.
The full graph is a hairball (about 3,350 nodes and 12,300 edges); use it once as an opening shot, then show these.

Run: uv run --env-file .env python -m lineage.graph.demo_queries [--check]
"""
from __future__ import annotations

import sys
import textwrap
from pathlib import Path

PAGE = "content/en/docs/concepts/policy/resource-quotas.md"
CLAIM = f"{PAGE}#quota-for-local-ephemeral-storage:1"

# (title, what to say, cypher, max elements)
QUERIES = [
    ("1. The hero path: a docs label, its feature gate and the gate's stage in every release",
     "Resource Quotas page -> section -> the 'alpha since v1.8' claim -> the gate it is about -> one STAGE_IN edge per release (alpha 1.7, beta 1.10, stable 1.25).",
     f"MATCH (p:DocPage {{path:'{PAGE}'}})-[r1:HAS_SECTION]->(s:DocSection {{anchor:'quota-for-local-ephemeral-storage'}})-[r2:HAS_CLAIM]->(c:Claim)-[r3:ABOUT]->(g:FeatureGate)-[r4:STAGE_IN]->(rel:Release)\n"
     "WHERE g.name = 'LocalStorageCapacityIsolation' AND r3.link_confidence >= 0.8\n"
     "RETURN p, r1, s, r2, c, r3, g, r4, rel", 60),
    ("2. The finding, the decision behind it and the team that owns it",
     "The detector's Finding node, the claim and gate it points at, the design document (KEP) that introduced the gate, and its owning team.",
     f"MATCH (f:Finding {{active:true}})-[r1:FOR_CLAIM]->(c:Claim {{id:'{CLAIM}'}}), (f)-[r2:FOR_GATE]->(g:FeatureGate), (f)-[r3:AS_OF]->(rel:Release)\n"
     "OPTIONAL MATCH (k:KEP)-[r4:INTRODUCES]->(g) WHERE r4.confidence >= 0.7\n"
     "OPTIONAL MATCH (k)-[r5:OWNED_BY]->(t:SIG)\n"
     "RETURN f, r1, c, r2, g, r3, rel, r4, k, r5, t", 40),
    ("3. How the link was made, and what a human did",
     "Both sibling gates were candidates at 0.79 each; the project owner verified the link by hand. The edge keeps the linker's own score.",
     f"MATCH (c:Claim {{id:'{CLAIM}'}})-[a:ABOUT]->(g:FeatureGate)\nRETURN c, a, g", 10),
    ("4. One gate's lifecycle",
     "LocalStorageCapacityIsolation across releases.",
     "MATCH (g:FeatureGate {name:'LocalStorageCapacityIsolation'})-[e:STAGE_IN]->(r:Release)\nRETURN g, e, r", 45),
    ("5. Ownership time travel: who approved the Job controller, and when",
     "Edges carry valid_from / valid_to as sampled release numbers: alculquicondor 130-132, mimowo from 132. Click an edge to see its properties and source_url.",
     "MATCH (p:Person)-[a:APPROVER_OF]->(c:CodePath {id:'kubernetes:pkg/controller/job'})\nRETURN p, a, c", 10),
    ("6. One team's ownership: sig-storage, the code it owns, who approves it",
     "SIG -> OWNS -> CodePath <- APPROVER_OF - Team <- MEMBER_OF - Person (people resolved through the team alias, current members only).",
     "MATCH (s:SIG {id:'sig-storage'})-[o:OWNS]->(c:CodePath)\n"
     "OPTIONAL MATCH (t:Team)-[a:APPROVER_OF]->(c) WHERE a.valid_to IS NULL\n"
     "OPTIONAL MATCH (p:Person)-[m:MEMBER_OF]->(t) WHERE m.valid_to IS NULL\n"
     "RETURN s, o, c, a, t, m, p", 80),
    ("7. Inheritance: a docs page's folder chain up to the root",
     "Ownership is inherited down the tree; the walk stops at content/en because its OWNERS sets no_parent_owners. (This shows the tree; the real query cuts the walk.)",
     "MATCH path = (c:CodePath {id:'website:content/en/docs/concepts/policy'})-[:CHILD_OF*0..]->(anc:CodePath)\nRETURN path", 20),
    ("8. Everything the detector wants a human to look at",
     "Findings, minor findings and review items with their reason. Use the table view.",
     "MATCH (f:Finding {active:true})\nRETURN f.severity AS severity, f.kind AS kind, f.message AS message ORDER BY severity, kind", 30),
]


def export() -> str:
    out = ["# Focused queries for the FalkorDB browser", "",
           "Open <http://localhost:3000>, log in with the password from `.env`, choose the `lineage` graph and paste a query. "
           "The whole graph is a hairball; these return small, readable subgraphs. Generated by `python -m lineage.graph.demo_queries`.", ""]
    for title, say, q, _ in QUERIES:
        out += [f"## {title}", "", say, "", "```cypher", textwrap.dedent(q).strip(), "```", ""]
    return "\n".join(out) + "\n"


def check(g=None, quiet: bool = False) -> int:
    from lineage.graph.client import get_graph

    g = g or get_graph()
    bad = 0
    for title, _, q, cap in QUERIES:
        res = g.ro_query(q)
        elements = set()
        for row in res.result_set:
            for cell in row:
                if hasattr(cell, "id") and hasattr(cell, "properties"):
                    elements.add((type(cell).__name__, cell.id))
                elif hasattr(cell, "nodes"):  # a path
                    elements |= {("Node", n.id) for n in cell.nodes()} | {("Edge", e.id) for e in cell.edges()}
        size = len(elements) or len(res.result_set)
        ok = 0 < size <= cap
        bad += not ok
        if not quiet or not ok:
            print(f"{'ok ' if ok else 'BAD'} {size:4d} elements (cap {cap:3d}) | {title}")
    return bad


if __name__ == "__main__":
    Path("docs/demo_queries.md").write_text(export())
    print("docs/demo_queries.md written")
    if "--check" in sys.argv:
        sys.exit(1 if check() else 0)
