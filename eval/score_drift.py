"""Two-stage drift evaluation (CLAUDE.md §12.A): (1) was the label linked to the right gate? (2) given the right gate, is the verdict right?

Run: uv run --env-file .env python -m eval.score_drift   -> prints and writes eval/results/drift_report.md

Honesty rules: every number says what it was measured on; AI-assisted audits are labelled as such; small samples are flagged.
"""
from __future__ import annotations

import json
import math
from collections import Counter
from pathlib import Path

from lineage.config import load_settings
from lineage.detect.drift import HistoryRow, evaluate_claim, run_detector
from lineage.graph.client import connect
from lineage.ingest.gates import Gate, StageRange, expand_to_releases
from lineage.ingest.keps import SNAPSHOT as KEPS
from lineage.link.linker import CONFIDENT, Linker, _SHORTCODE, read_jsonl
from eval.score_links import half, score

SNAP = Path("snapshot")


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    m = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return ((c - m) / d, (c + m) / d)


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.0f}%"


def history(gate: dict) -> list[HistoryRow]:
    g = Gate(**{**gate, "stages": [StageRange(s["stage"], s["from_version"], s["to_version"], s["default_value"], s["locked"]) for s in gate["stages"]]})
    return [HistoryRow(r["release_num"], r["release"], r["stage"], r["overlap"]) for r in expand_to_releases(g)]


def main() -> None:
    gates = read_jsonl(SNAP / "gates.jsonl")
    gate_by = {g["name"]: g for g in gates}
    labels = read_jsonl(SNAP / "doc_labels.jsonl")
    label_by = {x["id"]: x for x in labels}
    keps = read_jsonl(KEPS)
    out: list[str] = ["# Drift detector evaluation", "", f"Snapshot of 2026-10-15. Confident link = score >= {CONFIDENT}. Generated by `eval/score_drift.py`.", ""]

    # ---- Stage 1: linking -------------------------------------------------------------------------------
    out += ["## Stage 1: was the label linked to the right gate?", ""]
    known = [x for x in labels if x["kind"] == "gate_lookup" and x["gate_name"] in gate_by]
    A = [x for x in known if half(x["page_path"]) == "A"]
    B = [x for x in known if half(x["page_path"]) == "B"]
    noname = {"name_mention": 0.0, "name_bare": 0.0}
    out += ["### 1a. Proxy test: 265 claims whose gate is known (the gate-lookup shortcode is hidden)", "",
            "Pages are split in two halves by a stable hash; parameters were chosen on half A, half B is held out. "
            "**This flatters the linker**: every proxy claim has a gate, and 53% of their sections name it, versus 16% of the real hard-coded ones.", "",
            "| Setting | Half | Confident coverage | Confident precision | Top-1 accuracy |", "|---|---|---|---|---|"]
    for name, params in (("gate name visible", None), ("gate name hidden", noname)):
        lk = Linker(gates, params, keps)
        for h, sub in (("A (tuned)", A), ("B (held out)", B)):
            r = score(sub, lk)
            out.append(f"| {name} | {h} | {pct(r['confident_coverage'])} | {pct(r['confident_precision'])} | {pct(r['top1_accuracy'])} |")
    out.append("")

    audit = read_jsonl(Path("eval/link_audit.jsonl"))
    n, ok = len(audit), sum(a["verdict"] == "correct" for a in audit)
    lo, hi = wilson(ok, n)
    anch = [a for a in audit if a["name_mention_strength"] >= 0.9]
    aok = sum(a["verdict"] == "correct" for a in anch)
    out += ["### 1b. Audit of the confident links on the REAL hard-coded claims", "",
            f"Every confident link was read against its docs section. **AI-assisted audit (Claude); needs human verification by Nan or Abiram.**", "",
            f"- Confident links audited: **{n}**; correct **{ok}** ({pct(ok / n)}, 95% interval {pct(lo)}-{pct(hi)}); wrong **{n - ok}**.",
            f"- Anchored subset (gate name next to \"feature gate\"): **{len(anch)}** links, **{aok} correct** (too few to be conclusive).",
            "- The wrong links were: " + "; ".join(f"{a['claim_id'].split('/')[-1].split(':')[0].split('#')[1]} -> {a['linked_gate']}" for a in audit if a["verdict"] == "wrong") + ".",
            "- All wrong links were un-anchored, so the anchoring policy keeps them from becoming findings.", ""]

    links = read_jsonl(SNAP / "links.jsonl")
    current_confident = {l["claim_id"] for l in links if l["candidates"] and l["candidates"][0]["confidence"] >= CONFIDENT
                         and "contribute/style" not in label_by[l["claim_id"]]["page_path"]}
    audited = {a["claim_id"] for a in audit}
    if current_confident != audited:  # the audit is stale: the linker changed since it was done
        out += [f"> **WARNING: the link audit is out of date.** {len(current_confident - audited)} confident links are not audited and "
                f"{len(audited - current_confident)} audited links are no longer confident. Re-audit before quoting 1b.", ""]
    top = Counter()
    for l in links:
        lab = label_by[l["claim_id"]]
        if "contribute/style" in lab["page_path"]:
            continue
        c = l["candidates"]
        top["confident" if c and c[0]["confidence"] >= CONFIDENT else "possible only" if c else "unresolved"] += 1
    out += ["### 1c. Where the 186 drift-eligible claims land (before the hand-verified seed link)", "",
            f"labels found 453 (265 look their gate up and cannot go stale; 188 hard-coded, 2 of them in the style guide and excluded) | "
            f"**confident {top['confident']}** | possible only {top['possible only']} | unresolved {top['unresolved']}", ""]

    cases = read_jsonl(Path("eval/drift_cases.jsonl"))
    lk = Linker(gates, None, keps)
    out += ["### 1d. The 11 hand-picked cases", "", "| Case | Expected gate | Linker top result | Verdict |", "|---|---|---|---|"]
    tally = Counter()
    for c in cases:
        lab = label_by[c["claim_id"]]
        cands = lk.link(lab["section_text"], lab["doc_links"], lab["heading"], lab["page_doc_links"])
        topc = cands[0] if cands else None
        exp, bad = c["expected_gate"], c["forbidden_confident_gate"]
        if bad:
            v = "FAIL" if any(x.gate == bad and x.confidence >= CONFIDENT for x in cands) else "ok (not confidently linked to the wrong gate)"
        elif exp:
            hit = next((x for x in cands if x.gate == exp), None)
            v = "confident, correct" if hit and hit.confidence >= CONFIDENT and cands[0].gate == exp else "possible only" if hit else "missed"
        else:
            v = "no gate known: " + ("confident link (inspect)" if topc and topc.confidence >= CONFIDENT else "no confident link")
        tally[v.split(" (")[0]] += 1
        out.append(f"| {c['id']} | {exp or '-'} | {topc.gate + ' ' + str(topc.confidence) if topc else '-'} | {v} |")
    out += ["", "Summary: " + ", ".join(f"{k}: {v}" for k, v in tally.items()) + ". The seed case is below the bar automatically and is covered by the manually verified link (disclosed).", ""]

    # ---- Stage 2: detection given the right gate --------------------------------------------------------
    out += ["## Stage 2: given the right gate, is the verdict right?", "", "Uses the verified gate of each hand-picked case, so linking errors cannot leak in. "
           "Positive = the label should be reported stale; negative = the label is correct and must stay silent.", "",
           "| Case | Label | Expected | Detector says | OK |", "|---|---|---|---|---|"]
    tp = tn = fp = fn = 0
    for c in cases:
        if not c["gate_verified"] or c["expected_outcome"] == "ambiguous":
            continue
        g = gate_by[c["expected_gate"]]
        ev = evaluate_claim(c["claim_id"], c["claimed_stage"], c["claimed_since"], c["expected_gate"], g["removed"], history(g))
        says = ev.kind if ev else "silent"
        positive = c["expected_outcome"] == "positive"
        good = (ev is not None and ev.kind == "stale_stage") if positive else ev is None
        tp += positive and good
        fn += positive and not good
        tn += (not positive) and good
        fp += (not positive) and not good
        out.append(f"| {c['id']} | {c['claimed_stage']} {c['claimed_since']} | {'stale' if positive else 'silent'} | {says} | {'yes' if good else '**NO**'} |")
    out += ["", f"**True positive {tp}, true negative {tn}, false positive {fp}, false negative {fn}** (n={tp + tn + fp + fn}; small, so this checks the logic rather than measuring accuracy).", ""]

    # ---- End to end ---------------------------------------------------------------------------------------
    s = load_settings()
    g = connect(s).select_graph(s.falkordb_graph)
    results, stats = run_detector(g)
    fa = {a["claim_id"]: a for a in read_jsonl(Path("eval/finding_audit.jsonl"))}
    out += ["## End to end on the real pages", "", "| Counted | Number |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(stats.items())] + [""]
    real = [r for r in results if r.severity in ("finding", "minor")]
    out += ["Findings and minor findings, hand-checked (AI-assisted, needs human verification):", ""]
    for r in real:
        a = fa.get(r.claim_id)
        out.append(f"- **{r.kind}** `{r.claim_id.split('/')[-1]}`: {a['verdict'] if a else 'NOT AUDITED'}" + (f" ({a['note']})" if a else ""))
    nf = [r for r in real if r.severity == "finding"]
    tf = sum(1 for r in nf if fa.get(r.claim_id, {}).get("verdict") == "true_finding")
    out += ["", f"Finding precision on the real corpus: **{tf} of {len(nf)}** reported findings are real. This is a very small sample.",
            f"Review items (not findings, need a human look): {sum(r.severity == 'review' for r in results)}, not audited.", "",
            "## What this does not show", "",
            "- **Recall is unknown.** Many stale labels may sit among the 105 'possible only' and 10 unresolved claims; we cannot count them without a human labelling pass.",
            "- Many labels describe features that never had a gate, so they cannot be checked by this method at all.",
            "- Small samples throughout; all audits are AI-assisted and must be confirmed by a person before they are quoted as results."]
    Path("eval/results/drift_report.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
