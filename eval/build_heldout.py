"""Build a PRE-REGISTERED held-out question set: random entities, fixed seed, generated from the raw snapshot, frozen by hash before any run.

Why: the first gold set (eval/gold_questions.jsonl) was written by the same party that built the system and revised after seeing runs, so its
numbers are optimistic. Here no human picks the questions. A template turns a randomly drawn entity into a question and computes its answer from
snapshot/*.jsonl (not from the graph or the agent). Entities already used in the first gold set are excluded.

Rules (also written into eval/results/heldout_freeze.json):
  * the seed is fixed in this file BEFORE the set is generated; the generated file is hashed and the hash recorded BEFORE any system sees it
  * the set is run once; questions and answers are never edited afterwards. If one is found to be wrong, it is reported as wrong, not fixed;
    a corrected set would need a new seed and a new freeze record, and the old results stay published.
  * the "drift" category cannot be generated at random without making the truth depend on our own detector, so it is replaced here by
    "docs_to_gate" (which feature gate does a docs section describe?), a linking question whose answer is stated in the page itself.

Run: uv run python -m eval.build_heldout   (refuses to overwrite a frozen set)
"""
from __future__ import annotations

import hashlib
import json
import random
import sys
from datetime import datetime, timezone
from pathlib import Path

from eval import build_gold as G
from lineage.graph.loader import CROSS_CUTTING, is_bot, is_cherry_pick, nearest_codepath  # noqa: F401  (documented rules shared with the product)
from lineage.link.linker import read_jsonl

SEED = 20261016
PER_CATEGORY = 5
OUT = Path("eval/gold_heldout.jsonl")
FREEZE = Path("eval/results/heldout_freeze.json")
SNAP = Path("snapshot")

USED_DIRS = {"pkg/controller/job", "pkg/volume", "pkg/apis/core/v1", "staging/src/k8s.io/mount-utils"}
USED_GATES = {"LocalStorageCapacityIsolation", "AnyVolumeDataSource", "CronJobTimeZone", "VolumeSnapshotDataSource", "PodHostIPs", "NamespaceDefaultLabelName",
              "IdentifyPodOS", "PodPriority", "BlockVolume", "ConfigurableFSGroupPolicy", "KMSv2", "BoundServiceAccountTokenVolume"}
USED_SIGS = {"sig-storage", "sig-node"}
LABELS = read_jsonl(SNAP / "doc_labels.jsonl")
GATES = G.GATE
CODEPATHS = [c for c in read_jsonl(SNAP / "codepaths.jsonl") if c["repo"] == "kubernetes" and c["has_owners"] and c["dir"]]
LATEST = G.LATEST


def release(n: int) -> str:
    return f"1.{n - 100}"


def person_check(handles: list[str], many: int = 5) -> list[dict]:
    """All of them when there are few; otherwise any three (a long list should not be a memory test)."""
    return [{"all": handles}] if len(handles) <= many else [{"any": handles, "min": 3}]


def single_kep_gates() -> dict[str, dict]:
    """Gates listed in exactly ONE kep.yaml (so 'the design document behind G' is unambiguous) whose KEP has a known team and approvers."""
    by_gate: dict[str, list[dict]] = {}
    for k in G.KEP.values():
        for g in k["feature_gates"]:
            by_gate.setdefault(g, []).append(k)
    return {g: ks[0] for g, ks in by_gate.items() if len(ks) == 1 and g in GATES and g not in USED_GATES and ks[0]["owning_sig"] in G.SIG
            and ks[0]["approvers"] and ks[0]["status"] in ("implemented", "implementable")}


def build(rng: random.Random) -> list[dict]:
    out: list[dict] = []
    n = {"own": 0, "exp": 0, "tt": 0, "dl": 0, "dg": 0, "mh": 0, "un": 0}

    def add(prefix: str, cat: str, *args, **kw) -> None:
        n[prefix] += 1
        e = G.q(f"h_{prefix}{n[prefix]}", cat, *args, **kw)
        e["status"] = "HELD-OUT (pre-registered, generated by eval/build_heldout.py, never edited)"
        out.append(e)

    # ---- ownership: 3 folders, 1 chair question, 1 tech-lead question
    dirs = sorted(c["dir"] for c in CODEPATHS if c["dir"] not in USED_DIRS and G.people("kubernetes", c["dir"], "APPROVER_OF"))
    for d in rng.sample(dirs, 3):
        who = G.people("kubernetes", d, "APPROVER_OF")
        add("own", "ownership", f"Who are the individual approvers, not teams, listed in the OWNERS file of {d} in kubernetes/kubernetes today?", ", ".join(who),
            person_check(who), G.src("kubernetes", d, "APPROVER_OF"), "owners_of", {"path": d})
    sigs = sorted(s for s, v in G.SIG.items() if s not in USED_SIGS and v["group_type"] == "sig")
    chairs_pool = [s for s in sigs if G.leaders(s, "chair")]
    s = rng.choice(chairs_pool)
    add("own", "ownership", f"Who are the chairs of {s}?", ", ".join(G.leaders(s, "chair")), [{"all": G.alts(G.leaders(s, "chair"))}], [G.SIG[s]["source_url"]], "sig_leaders", {"sig": s})
    s2 = rng.choice([x for x in sigs if G.leaders(x, "tech_lead") and x != s])
    add("own", "ownership", f"Who are the tech leads of {s2}?", ", ".join(G.leaders(s2, "tech_lead")), [{"all": G.alts(G.leaders(s2, "tech_lead"))}], [G.SIG[s2]["source_url"]], "sig_leaders", {"sig": s2})

    # ---- expertise: who actually reviews a folder (from raw PR data, same documented rules as the product)
    pool = []
    for c in CODEPATHS:
        if c["dir"] in USED_DIRS or c["dir"].count("/") < 1:
            continue
        top, urls = G.active_reviewers(c["dir"])
        if len(top) >= 6:
            pool.append((c["dir"], top, urls))
    for d, top, urls in rng.sample(sorted(pool), PER_CATEGORY):
        add("exp", "expertise", f"Who actively reviews changes to {d}? Name two people.", f"two of: {', '.join(top[:6])}", [{"any": top, "min": 2}], urls, "experts_for", {"path": d},
            "from raw PR data: distinct merged master PRs reviewed in the last 12 months; backports and repo-wide PRs excluded")

    # ---- time travel: 3 approver-history questions, 2 gate-stage-as-of questions
    changed_set = set()
    for e in G.E:  # approvers whose role ended inside the sampled history: the answer differs between releases
        if e["repo"] == "kubernetes" and e["role"] == "APPROVER_OF" and e["subject_kind"] == "person" and e["valid_to"] and e["dir"] not in USED_DIRS and "/" in e["dir"]:
            for r in range(e["valid_from"], e["valid_to"]):
                if r < LATEST and G.people("kubernetes", e["dir"], "APPROVER_OF", r):
                    changed_set.add((e["dir"], r))
    by_dir: dict[str, list[int]] = {}
    for d, r in sorted(changed_set):
        by_dir.setdefault(d, []).append(r)
    for d in rng.sample(sorted(by_dir), 3):  # three DIFFERENT folders
        r = rng.choice(by_dir[d])
        who = G.people("kubernetes", d, "APPROVER_OF", r)
        add("tt", "time_travel", f"Who were the individual approvers of {d} in release {release(r)}?", ", ".join(who), person_check(who), G.src("kubernetes", d, "APPROVER_OF", r),
            "owners_of", {"path": d, "as_of": release(r)}, "an ownership change happens at this path in the sampled history")
    stage_pool = []
    for name, g in sorted(GATES.items()):
        if name in USED_GATES or len({s["stage"] for s in g["stages"]}) < 2:
            continue
        for s in g["stages"]:
            if s["to_version"] and s["from_version"] != s["to_version"]:
                lo, hi = int(s["from_version"].split(".")[1]), int(s["to_version"].split(".")[1])
                minor = (lo + hi) // 2  # the middle of the span, never a boundary release
                covering = {x["stage"] for x in g["stages"] if int(x["from_version"].split(".")[1]) <= minor <= int(x["to_version"].split(".")[1] if x["to_version"] else 99)}
                if covering == {s["stage"]}:  # exactly one stage that release, so the question has one answer
                    stage_pool.append((name, s["stage"], minor))
    for name, stage, minor in rng.sample(sorted(stage_pool), 2):
        add("tt", "time_travel", f"What maturity stage was the {name} feature gate in during release 1.{minor}?", stage, [{"all": [stage]}], [GATES[name]["source_url"]], "gate_timeline", {"gate": name})

    # ---- decision lineage on gates listed in exactly one kep.yaml
    pool = single_kep_gates()
    by_sig: dict[str, list[str]] = {}
    for g_, k_ in sorted(pool.items()):
        by_sig.setdefault(k_["owning_sig"], []).append(g_)
    stable_ok = [s_ for s_ in sorted(by_sig) if any(pool[g_]["milestone"].get("stable") for g_ in by_sig[s_])]
    dl_sigs = rng.sample([s_ for s_ in sorted(by_sig) if len(by_sig[s_]) >= 1], 4)
    last = rng.choice([s_ for s_ in stable_ok if s_ not in dl_sigs])
    used_gates: list[str] = []
    for i, sig_ in enumerate(dl_sigs):
        g = rng.choice(by_sig[sig_]); k = pool[g]; used_gates.append(g)
        if i < 2:
            add("dl", "decision_lineage", f"Which team owns the design document behind the {g} feature gate?", k["owning_sig"], [{"all": [k["owning_sig"]]}], [k["source_url"]], "decision_lineage", {"kep_or_gate": g})
        else:
            add("dl", "decision_lineage", f"Who approved the design document behind the {g} feature gate?", ", ".join(k["approvers"]), person_check(k["approvers"], 4), [k["source_url"]], "decision_lineage", {"kep_or_gate": g})
    g = rng.choice([x for x in by_sig[last] if pool[x]["milestone"].get("stable")]); k = pool[g]; used_gates.append(g)
    add("dl", "decision_lineage", f"In which Kubernetes release did the design document behind {g} reach stable?", k["milestone"]["stable"], [{"all": [k["milestone"]["stable"].lstrip("v")]}], [k["source_url"]], "decision_lineage", {"kep_or_gate": g})

    # ---- docs to gate: a docs section whose badge names its gate in the page source
    lookups = [x for x in LABELS if x["kind"] == "gate_lookup" and x["gate_name"] in GATES and x["heading"] and x["gate_name"] not in USED_GATES]
    heads: dict[tuple, int] = {}
    for x in lookups:
        heads[(x["page_path"], x["heading"])] = heads.get((x["page_path"], x["heading"]), 0) + 1
    uniq = sorted((x for x in lookups if heads[(x["page_path"], x["heading"])] == 1), key=lambda x: x["id"])
    for x in rng.sample(uniq, PER_CATEGORY):
        add("dg", "docs_to_gate", f"Which feature gate does the \"{x['heading']}\" section of the \"{x['page_title']}\" documentation page describe?", x["gate_name"], [{"all": [x["gate_name"]]}],
            [x["source_url"]], "doc_claims", {"page_or_section": x["heading"]}, "the page's own badge names the gate (feature_gate_name=)")

    # ---- multi-hop: gate -> design document -> owning team -> chairs (five different teams)
    mh_sigs = rng.sample([s_ for s_ in sorted(by_sig) if G.leaders(s_, "chair")], PER_CATEGORY)
    for sig in mh_sigs:
        g = rng.choice([x for x in by_sig[sig] if x not in used_gates] or by_sig[sig]); k = pool[g]
        add("mh", "multi_hop", f"Who chairs the team that owns the design document behind the {g} feature gate?", ", ".join(G.leaders(sig, "chair")), [{"all": G.alts(G.leaders(sig, "chair"))}],
            [k["source_url"], G.SIG[sig]["source_url"]], "decision_lineage", {"kep_or_gate": g}, "needs two hops: gate -> design document -> team -> chairs")

    # ---- unanswerable (the right behaviour is a refusal)
    d = rng.choice(dirs); s3 = rng.choice(sigs)
    fake = "".join(rng.choice("ABCDEFGHIJKLMNOPRSTUVWXYZ") for _ in range(3)) + "PodTeleportation"
    for qid, text, why in [("a", f"Who approved the design document behind the {fake} feature gate?", "the gate does not exist"),
                           ("b", f"Who will be the approvers of {d} in release 1.45?", "the future is not in the data"),
                           ("c", f"What is the home address of the chair of {s3}?", "personal data is not held"),
                           ("d", "How many pull requests were reviewed in the kubernetes/enhancements repository last year?", "pull-request data covers kubernetes/kubernetes only")]:
        n["un"] += 1
        out.append({"id": f"h_un{n['un']}", "category": "unanswerable", "question": text, "answer": "refusal expected (insufficient evidence)", "checks": [{"refusal": True}], "sources": [],
                    "oracle_tool": None, "notes": why, "status": "HELD-OUT (pre-registered, generated by eval/build_heldout.py, never edited)"})
    return out


def main() -> None:
    if OUT.exists() and FREEZE.exists():
        sys.exit(f"{OUT} is frozen (see {FREEZE}); refusing to regenerate. A new set needs a new SEED and a new freeze record.")
    qs = build(random.Random(SEED))
    body = "".join(json.dumps(q, sort_keys=True) + "\n" for q in qs)
    OUT.write_text(body)
    FREEZE.parent.mkdir(parents=True, exist_ok=True)
    FREEZE.write_text(json.dumps({"seed": SEED, "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "sha256": hashlib.sha256(body.encode()).hexdigest(),
                                  "questions": len(qs), "revisions_before_first_run": ["generator revised ONCE after reading the first draw (before any system saw it): time-travel folders must be distinct and not a bare top-level folder; decision-lineage and multi-hop questions must cover distinct owning teams. No system output was looked at."], "rules": __doc__.split("Rules (also written into eval/results/heldout_freeze.json):")[1].split("Run:")[0].strip()}, indent=1) + "\n")
    from collections import Counter
    print(len(qs), "questions:", dict(Counter(q["category"] for q in qs)), "| sha256", hashlib.sha256(body.encode()).hexdigest()[:16])


if __name__ == "__main__":
    main()
